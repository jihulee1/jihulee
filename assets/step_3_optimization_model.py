# STEP 3: WATER ALLOCATION OPTIMIZATION  (Linear Program)

# Goal: decide how to route each treated stream to each end-use so
#       that freshwater intake + operating cost is minimized, while
#       every demand is met at its required water quality.
#
# Builds on: Step 1 (streams, demands) + Step 2 WAVE PRO (RO numbers)
# Run in Google Colab:   !pip install pulp

import pulp
import pandas as pd

# SECTION 1 — INPUTS

# ---- Fab-wide demand (from Step 1) ----
TOTAL_WATER_DEMAND = 30000      # m3/day

# ---- END-USES (demands): how much each needs + quality limit (TDS) ----
# UPW limit set to RO-permeate quality (final polish by EDI is downstream)
demands = {
    'upw':     {'flow': TOTAL_WATER_DEMAND * 0.72, 'tds_limit': 2.0},
    'cooling': {'flow': TOTAL_WATER_DEMAND * 0.18, 'tds_limit': 600},
    'utility': {'flow': TOTAL_WATER_DEMAND * 0.10, 'tds_limit': 1000},
}

# ---- SOURCES OF REUSE WATER ----
# upw_rinse = REAL WAVE PRO numbers (TP-2 Case 1):
#   system permeate 8,674 m3/d @ 1.498 mg/L, recovery 67.5%
# other four streams = still Step-1 estimates (model in WAVE later)
# Each source: available flow (m3/d) + its TDS (mg/L)
RO_SYS_RECOVERY = 0.675        # WAVE system recovery (dual-pass)
RO_REMOVAL      = 0.99582      # WAVE: 358 -> 1.498 mg/L

# captured volumes routed to RO (from Step 1 capture fractions x wastewater)
captured = {
    'upw_rinse': 12852.0,   # feeds WAVE design
    'hf_acid':   388.8,
    'copper':    259.2,
    'cooling':   1595.7,
    'utility':   600.0,
}
# feed TDS of each stream (Step 1)
feed_tds = {'upw_rinse':358,'hf_acid':1200,'copper':900,'cooling':1500,'utility':700}

# Build RO-permeate sources: flow = captured x recovery, tds = feed x (1-removal)
ro_permeate = {}
for k, cap in captured.items():
    ro_permeate[k] = {
        'flow': cap * RO_SYS_RECOVERY,
        'tds':  feed_tds[k] * (1 - RO_REMOVAL),
    }
# Override upw_rinse with EXACT WAVE system-permeate numbers
ro_permeate['upw_rinse'] = {'flow': 8674.0, 'tds': 1.498}

# ---- Fresh city water: unlimited, costs money ----
TDS_FRESH = 300

# ---- Economics (document these sources in your report) ----
FRESH_COST   = 1.00     # $/m3 city water (placeholder - use local price)
ENERGY_COST  = 0.12     # $/kWh
SPEC_ENERGY  = 0.838    # kWh/m3  <-- WAVE final-permeate specific energy

# SECTION 2 — BUILD THE MODEL

model = pulp.LpProblem('fab_water_allocation', pulp.LpMinimize)

sources = list(ro_permeate.keys())

# --- Decision variables ---
# x[s][d] = m3/day of RO-permeate source s routed to demand d
x = {s: {d: pulp.LpVariable(f'x_{s}_{d}', lowBound=0) for d in demands}
     for s in sources}
# fresh[d] = m3/day of fresh city water to demand d
fresh = {d: pulp.LpVariable(f'fresh_{d}', lowBound=0) for d in demands}

# SECTION 3 — OBJECTIVE  (minimize freshwater + energy cost)

cost_fresh  = FRESH_COST * pulp.lpSum(fresh[d] for d in demands)
cost_energy = ENERGY_COST * SPEC_ENERGY * pulp.lpSum(
    x[s][d] for s in sources for d in demands)
model += cost_fresh + cost_energy, 'total_operating_cost'

# SECTION 4 — CONSTRAINTS

# (1) Meet each demand's flow exactly (reuse + fresh = demand)
for d in demands:
    model += (pulp.lpSum(x[s][d] for s in sources) + fresh[d]
              == demands[d]['flow']), f'flow_{d}'

# (2) Blended TDS <= limit, written in linear mass-load form
#     sum(flow*tds) + fresh*tds_fresh  <=  limit * total_flow
for d in demands:
    model += (pulp.lpSum(x[s][d] * ro_permeate[s]['tds'] for s in sources)
              + fresh[d] * TDS_FRESH
              <= demands[d]['tds_limit'] * demands[d]['flow']), f'qual_{d}'

# SECTION 5 — SOLVE

model.solve(pulp.PULP_CBC_CMD(msg=0))
print("="*60)
print("SOLVE STATUS:", pulp.LpStatus[model.status])
print(f"Operating cost: ${pulp.value(model.objective):,.2f}/day")
print("="*60)

# SECTION 6 — RESULTS

rows = []
for d in demands:
    for s in sources:
        v = x[s][d].value() or 0
        if v > 1e-6:
            rows.append({'demand': d, 'source': f'ro_{s}',
                         'flow_m3d': round(v,1),
                         'src_tds': round(ro_permeate[s]['tds'],2)})
    fv = fresh[d].value() or 0
    if fv > 1e-6:
        rows.append({'demand': d, 'source': 'FRESH',
                     'flow_m3d': round(fv,1), 'src_tds': TDS_FRESH})
alloc = pd.DataFrame(rows)
print("\n--- OPTIMAL ROUTING ---")
print(alloc.to_string(index=False))

# ---- Headline metrics ----
total_fresh = sum((fresh[d].value() or 0) for d in demands)
total_reuse = sum((x[s][d].value() or 0) for s in sources for d in demands)
print("\n--- HEADLINE RESULTS ---")
print(f"Freshwater intake : {total_fresh:,.0f} m3/day")
print(f"Water reused      : {total_reuse:,.0f} m3/day")
print(f"Reuse rate        : {total_reuse/TOTAL_WATER_DEMAND*100:.1f}%")
print(f"  (Step 1 manual capture gave 39.2% - compare!)")

# ---- Verify blended quality actually meets limits ----
print("\n--- QUALITY DELIVERED (must be <= limit) ---")
for d in demands:
    load = sum((x[s][d].value() or 0)*ro_permeate[s]['tds'] for s in sources) \
           + (fresh[d].value() or 0)*TDS_FRESH
    blended = load / demands[d]['flow']
    ok = "OK" if blended <= demands[d]['tds_limit']+1e-6 else "VIOLATION"
    print(f"  {d:8s}: {blended:8.2f} mg/L  (limit {demands[d]['tds_limit']:>6}) {ok}")