#Set up
import pandas as pd
import numpy as np

pd.set_option('display.float_format', lambda x: f'{x:,.2f}')
print("Libraries loaded.")

# Global assumptions for a Taylor-class advanced logic fab
# All flows in cubic meters per day (m3/day)

# Fab scale
TOTAL_WATER_DEMAND = 30000      # m3/day total water used across the fab

# Demand split by end-use (what quality each NEEDS)
FRAC_UPW     = 0.72
FRAC_COOLING = 0.18
FRAC_UTILITY = 0.10

# Quality limits each END-USE supply must meet (TDS, mg/L)
TDS_LIMIT_UPW     = 0.001
TDS_LIMIT_COOLING = 600
TDS_LIMIT_UTILITY = 1000

# Incoming city water
TDS_CITY_WATER = 300

# DISCHARGE PERMIT LIMITS (what water leaving the fence must meet)
PERMIT_PH_LOW    = 6.0           # pH must be between 6 and 9
PERMIT_PH_HIGH   = 9.0
PERMIT_FLUORIDE  = 4.0           # mg/L
PERMIT_COPPER    = 1.0           # mg/L
PERMIT_TDS       = 1000          # mg/L (varies by municipality)

# Treatment performance
RO_RECOVERY    = 0.75            # fraction of RO feed that becomes permeate
RO_TDS_REMOVAL = 0.98
COOLING_EVAP_LOSS = 0.015

# Discharge pretreatment removal efficiencies (literature-based assumptions)
NEUTRALIZATION_SETS_PH = 7.0     # neutralization brings pH to ~neutral
FLUORIDE_REMOVAL = 0.95          # CaF2 precipitation removes ~95% of fluoride
COPPER_REMOVAL   = 0.98          # copper IX removes ~98% of copper

print("Assumptions set.")

# Cell 3: Define the segregrated streams
# Each stream: flow (m3/day) + contaminant loads in the USED water.
# pH is the raw stream pH; fluoride & copper in mg/L; tds in mg/L.
# 'needs' lists which discharge-pretreatment units apply if discharged.

#separates waste into 5 specialized streams
streams = {
    # Clean UPW rinse — lightly used, best reuse candidate, no special contaminants
    # 70% of total UPW demand + low TDS + near neutral pH
    'upw_rinse': {
        'flow': TOTAL_WATER_DEMAND * FRAC_UPW * 0.70,
        'pH': 6.8, 'fluoride': 2.0, 'copper': 0.1, 'tds': 350,
        'needs': [],
    },
    # HF / Waste from chemical etching (highly acidic + highly contaminated + High fluoride)
    'hf_acid': {
        'flow': TOTAL_WATER_DEMAND * FRAC_UPW * 0.18,
        'pH': 2.5, 'fluoride': 800, 'copper': 0.2, 'tds': 1200,
        'needs': ['neutralize', 'fluoride'],
    },
    # Copper-bearing stream (interconnect processing)
    # High Copper concentration
    'copper': {
        'flow': TOTAL_WATER_DEMAND * FRAC_UPW * 0.12,
        'pH': 4.0, 'fluoride': 5.0, 'copper': 40, 'tds': 900,
        'needs': ['neutralize', 'copper'],
    },
    # Cooling tower blowdown — concentrated minerals, evaporation loss
    'cooling': {
        'flow': TOTAL_WATER_DEMAND * FRAC_COOLING,
        'pH': 8.2, 'fluoride': 3.0, 'copper': 0.3, 'tds': 1500,
        'needs': [],
    },
    # Scrubbers / facilities — mild
    'utility': {
        'flow': TOTAL_WATER_DEMAND * FRAC_UTILITY,
        'pH': 7.0, 'fluoride': 4.0, 'copper': 0.5, 'tds': 700,
        'needs': ['neutralize'],
    },
}

# Capture fraction = how much of each stream we send to REUSE treatment (RO)
# vs. route to discharge. This is the lever your Step 3 optimization will tune.
capture = {
    'upw_rinse': 0.85,   # clean -> reuse most of it
    'hf_acid':   0.10,   # mostly discharge after pretreatment
    'copper':    0.10,
    'cooling':   0.30,
    'utility':   0.20,
}

df_streams = pd.DataFrame(streams).T
df_streams['capture'] = pd.Series(capture)
df_streams

# Cell 4: Discharge pretreatment function
def discharge_treatment(stream):
    """Apply pretreatment units this stream needs, return treated quality."""
    pH  = stream['pH']
    f   = stream['fluoride']
    cu  = stream['copper']
    tds = stream['tds']

    if 'neutralize' in stream['needs']:
        pH = NEUTRALIZATION_SETS_PH
    if 'fluoride' in stream['needs']:
        f  = f * (1 - FLUORIDE_REMOVAL)
    if 'copper' in stream['needs']:
        cu = cu * (1 - COPPER_REMOVAL)

    return {'pH': pH, 'fluoride': f, 'copper': cu, 'tds': tds}

def check_permit(q):
    """Return True if a treated-discharge quality dict meets all permit limits."""
    return (PERMIT_PH_LOW <= q['pH'] <= PERMIT_PH_HIGH
            and q['fluoride'] <= PERMIT_FLUORIDE
            and q['copper']   <= PERMIT_COPPER
            and q['tds']      <= PERMIT_TDS)

# Cell 5: Reuse treatment + trace every system
def reuse_treatment(flow, tds):
    """RO on captured water: returns recovered permeate flow, its TDS, and brine."""
    recovered = flow * RO_RECOVERY
    brine     = flow * (1 - RO_RECOVERY)
    recovered_tds = tds * (1 - RO_TDS_REMOVAL)
    return recovered, recovered_tds, brine

rows = []
for name, s in streams.items():
    evap = s['flow'] * (COOLING_EVAP_LOSS if name == 'cooling' else 0.0)
    wastewater = s['flow'] - evap

    captured   = wastewater * capture[name]        # -> reuse train (RO)
    to_discharge = wastewater - captured           # -> discharge train

    # Reuse path
    recovered, rec_tds, brine = reuse_treatment(captured, s['tds'])

    # Discharge path: pretreat + brine from RO also goes to discharge
    treated = discharge_treatment(s)
    discharged_total = to_discharge + brine
    compliant = check_permit(treated)

    rows.append({
        'stream': name, 'flow': s['flow'], 'evaporated': evap,
        'captured': captured, 'recovered': recovered, 'recovered_tds': rec_tds,
        'discharged': discharged_total,
        'disch_F': treated['fluoride'], 'disch_Cu': treated['copper'],
        'disch_pH': treated['pH'], 'permit_ok': compliant,
    })

df = pd.DataFrame(rows).set_index('stream')
df

# Cell 6: Overall balance + both headline results
total_demand     = sum(s['flow'] for s in streams.values())
total_recovered  = df['recovered'].sum()
total_discharged = df['discharged'].sum()
total_evaporated = df['evaporated'].sum()

freshwater_intake = total_demand - total_recovered
reuse_rate = total_recovered / total_demand
all_compliant = df['permit_ok'].all()

print("=== WATER BALANCE ===")
print(f"Total demand:       {total_demand:,.0f} m3/day")
print(f"Reclaimed & reused: {total_recovered:,.0f} m3/day")
print(f"Freshwater intake:  {freshwater_intake:,.0f} m3/day")
print(f"Discharged:         {total_discharged:,.0f} m3/day")
print(f"Evaporated (lost):  {total_evaporated:,.0f} m3/day")
print(f"--> Reuse rate:     {reuse_rate*100:.1f}%")
print(f"--> All streams meet discharge permit: {all_compliant}")

# Cell 7: Mass balance check
water_in  = freshwater_intake + total_recovered
water_out = total_discharged + total_evaporated + total_recovered
print(f"IN:  {water_in:,.2f}   OUT: {water_out:,.2f}   diff: {abs(water_in-water_out):,.4f}")
assert abs(water_in - water_out) < 1.0, "Mass balance does not close!"
print("Mass balance closes. ✓")

